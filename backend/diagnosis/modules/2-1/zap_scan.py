"""ZAP integration for guideline 2-1 — same upload probe matrix over ZAP sendRequest.

Auth headers are attached explicitly per-request (same as the httpx phase) —
ZAP's Replacer is not needed here because every probe is sent via
``zap.core.sendRequest`` with our own headers already in the raw request, not
generated by ZAP itself (unlike spider/active-scan crawling, which does need
the Replacer). Routing through ZAP means every probe lands in ZAP's
Sites/History and gets passively scanned like normal proxied traffic, so we
piggy-back on ZAP's own passive rules (e.g. X-Content-Type-Options missing,
Directory Browsing) as a supplemental signal on top of our own findings.
"""

from __future__ import annotations

